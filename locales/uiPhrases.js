const EN_TO_TH = Object.fromEntries(
  Object.entries(UI_PHRASES).map(([th, en]) => [en, th])
);

export function translateUiText(value, language) {
  if (typeof value !== "string") return value;

  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const text = value.trim();

  if (!text) return value;

  let translated = text;

  if (language === "en") {
    translated = UI_PHRASES[text] ?? text;

    if (translated === text) {
      for (const pattern of UI_PATTERNS) {
        const match = text.match(pattern.th);
        if (match) {
          translated = pattern.en(match);
          break;
        }
      }
    }

    // ค่าจากฐานข้อมูลที่แสดงเดี่ยว ๆ หรืออยู่ในข้อความทั่วไป
    if (translated === text) {
      translated = translateMasterDataText(text, "en");
    }
  } else {
    translated = EN_TO_TH[text] ?? text;

    if (translated === text) {
      for (const pattern of UI_PATTERNS) {
        const match = text.match(pattern.enRegex);
        if (match) {
          translated = pattern.thValue(match);
          break;
        }
      }
    }

    if (translated === text) {
      translated = translateMasterDataText(text, "th");
    }
  }

  return `${leading}${translated}${trailing}`;
}
