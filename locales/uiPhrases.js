const MASTER_EN_TO_TH = Object.fromEntries(
  Object.entries(MASTER_DATA_PHRASES).map(([th, en]) => [en, th])
);

export function translateMasterDataText(value, language) {
  if (typeof value !== "string" || !value) return value;

  const source = language === "en" ? MASTER_DATA_PHRASES : MASTER_EN_TO_TH;
  let output = value;

  // ยาวก่อนสั้น เพื่อไม่ให้คำสั้นไปแทนอยู่ข้างในชื่อรายการที่ยาวกว่า
  const entries = Object.entries(source).sort(
    ([left], [right]) => right.length - left.length
  );

  for (const [from, to] of entries) {
    output = output.split(from).join(to);
  }

  return output;
}

